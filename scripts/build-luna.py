#!/usr/bin/env python3
"""Build scripts/luna.py from the fragments in scripts/luna_cli/.

The fragments are consecutive slices of ONE module (they share a namespace and
are not importable on their own); they are concatenated in filename order. The
generated scripts/luna.py stays a single runnable file, so the installed shim,
`luna update`, `luna fleet install` and the in-Steam add-on keep working.

    python3 scripts/build-luna.py           rewrite scripts/luna.py
    python3 scripts/build-luna.py --check   exit 1 if scripts/luna.py is stale
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = HERE / 'luna_cli'
TARGET = HERE / 'luna.py'
NOTICE = ('# GENERATED by scripts/build-luna.py from scripts/luna_cli/*.py - do not edit;\n'
          '# edit the fragments and run `python3 scripts/build-luna.py`.\n')


def build():
    parts = sorted(SOURCES.glob('*.py'))
    if not parts:
        raise SystemExit('no fragments in %s' % SOURCES)
    text = ''.join(p.read_text(encoding='utf-8') for p in parts)
    shebang, rest = text.split('\n', 1)
    return shebang + '\n' + NOTICE + rest


def main(argv):
    text = build()
    if '--check' in argv:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != text:
            print('scripts/luna.py is stale; run: python3 scripts/build-luna.py', file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
